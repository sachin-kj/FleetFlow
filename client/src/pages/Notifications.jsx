import { useState, useEffect } from "react";
import {
  Bell,
  CheckCircle2,
  AlertTriangle,
  Package,
  Radio,
  Clock,
  Trash2,
  CheckCheck
} from "lucide-react";
import api from "../api";
import Badge from "../components/common/Badge";

export default function Notifications() {
  const [notifications, setNotifications] = useState([]);
  const [unreadCount, setUnreadCount] = useState(0);
  const [filter, setFilter] = useState("ALL");
  const [loading, setLoading] = useState(true);

  async function loadNotifications() {
    try {
      const { data } = await api.get("/fleet/notifications");
      setNotifications(data.notifications || []);
      setUnreadCount(data.unreadCount || 0);
    } catch (err) {
      console.error("Failed to load notifications:", err);
    } finally {
      setLoading(false);
    }
  }

  useEffect(() => {
    loadNotifications();
  }, []);

  async function markAsRead(id) {
    try {
      await api.patch(`/fleet/notifications/${id}/read`);
      setNotifications((prev) =>
        prev.map((n) => (n._id === id ? { ...n, read: true, readAt: new Date() } : n))
      );
      setUnreadCount((c) => Math.max(0, c - 1));
    } catch (err) {
      console.error(err);
    }
  }

  async function markAllAsRead() {
    try {
      await api.post("/fleet/notifications/read-all");
      setNotifications((prev) =>
        prev.map((n) => ({ ...n, read: true, readAt: new Date() }))
      );
      setUnreadCount(0);
    } catch (err) {
      console.error(err);
    }
  }

  const filtered = notifications.filter((n) => {
    if (filter === "ALL") return true;
    if (filter === "UNREAD") return !n.read;
    return n.type === filter;
  });

  return (
    <div className="space-y-6 max-w-4xl mx-auto">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 bg-white p-6 rounded-2xl border border-slate-200/80 shadow-[0_1px_3px_rgba(0,0,0,0.02)]">
        <div>
          <div className="flex items-center gap-2">
            <h1 className="font-display text-2xl font-extrabold text-slate-900">
              Notification Center
            </h1>
            {unreadCount > 0 && (
              <span className="px-2 py-0.5 rounded-full bg-blue-600 text-white font-bold text-xs">
                {unreadCount} unread
              </span>
            )}
          </div>
          <p className="text-xs text-slate-500 mt-1">
            Real-time alerts generated by BullMQ workers and dispatch triggers.
          </p>
        </div>

        {unreadCount > 0 && (
          <button
            onClick={markAllAsRead}
            className="px-4 py-2 rounded-xl border border-slate-200 bg-white hover:bg-slate-50 text-slate-700 font-bold text-xs flex items-center gap-1.5 transition"
          >
            <CheckCheck size={15} /> Mark All as Read
          </button>
        )}
      </div>

      {/* Filter Tabs */}
      <div className="flex flex-wrap items-center gap-1.5 text-xs font-semibold">
        {[
          { key: "ALL", label: "All Alerts" },
          { key: "UNREAD", label: "Unread" },
          { key: "BREAKDOWN", label: "Breakdowns" },
          { key: "ASSIGNMENT", label: "Assignments" },
          { key: "RECOVERY", label: "Recovery" },
          { key: "SYSTEM_ALERT", label: "System SLA" }
        ].map((tab) => (
          <button
            key={tab.key}
            onClick={() => setFilter(tab.key)}
            className={`px-3.5 py-1.5 rounded-xl transition ${
              filter === tab.key
                ? "bg-blue-600 text-white shadow-sm"
                : "bg-white text-slate-600 border border-slate-200 hover:bg-slate-50"
            }`}
          >
            {tab.label}
          </button>
        ))}
      </div>

      {/* List */}
      <div className="space-y-3">
        {filtered.map((n) => (
          <div
            key={n._id}
            className={`p-5 rounded-2xl border transition flex items-start justify-between gap-4 ${
              !n.read
                ? "bg-white border-blue-200 shadow-sm ring-1 ring-blue-500/10"
                : "bg-white/80 border-slate-200/80 text-slate-500"
            }`}
          >
            <div className="flex items-start gap-3.5">
              <div
                className={`w-9 h-9 rounded-xl flex items-center justify-center shrink-0 mt-0.5 ${
                  n.type === "BREAKDOWN" || n.type === "RECOVERY"
                    ? "bg-rose-50 text-rose-600"
                    : n.type === "ASSIGNMENT"
                    ? "bg-blue-50 text-blue-600"
                    : "bg-slate-100 text-slate-600"
                }`}
              >
                {n.type === "BREAKDOWN" ? (
                  <AlertTriangle size={18} />
                ) : n.type === "ASSIGNMENT" ? (
                  <Package size={18} />
                ) : (
                  <Bell size={18} />
                )}
              </div>

              <div>
                <div className="flex items-center gap-2">
                  <h4 className="font-display font-bold text-sm text-slate-900 leading-tight">
                    {n.title}
                  </h4>
                  <Badge status={n.type} size="xs" />
                </div>
                <p className="text-xs text-slate-600 mt-1 leading-relaxed">{n.message}</p>
                <span className="text-[10px] text-slate-400 block mt-2">
                  {new Date(n.createdAt).toLocaleString()}
                </span>
              </div>
            </div>

            {!n.read && (
              <button
                onClick={() => markAsRead(n._id)}
                className="text-xs font-bold text-blue-600 hover:text-blue-700 shrink-0 p-1.5"
                title="Mark read"
              >
                <CheckCircle2 size={16} />
              </button>
            )}
          </div>
        ))}

        {filtered.length === 0 && (
          <div className="bg-white p-12 text-center rounded-2xl border border-slate-200/80 text-slate-400 text-xs">
            No notifications in this category.
          </div>
        )}
      </div>
    </div>
  );
}
